// Copy the demo shim, its fixtures and the product media into one app.
// Runs before `dev` and `build` in each app: node ../scripts/sync-shared.mjs <app>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const app = process.argv[2];
const targets = {
  storefront: { demo: "storefront/src/demo", pub: "storefront/public" },
  admin: { demo: "admin/demo", pub: "admin/public" },
};
const target = targets[app];
if (!target) throw new Error(`usage: sync-shared.mjs ${Object.keys(targets).join("|")}`);

const demoDir = path.join(root, target.demo);
fs.mkdirSync(demoDir, { recursive: true });
for (const file of ["demo-api.ts", "demo-config.ts", "server-fetch.ts", "fixtures.d.ts"]) {
  fs.copyFileSync(path.join(root, "shared", file), path.join(demoDir, file));
}

// JSON.parse of a string literal: the fastest way to ship a big object, and it
// keeps the bundler from walking megabytes of object-literal syntax.
const raw = fs.readFileSync(path.join(root, "fixtures", `${app}.json`), "utf8");
fs.writeFileSync(
  path.join(demoDir, "fixtures.js"),
  `// Generated by scripts/sync-shared.mjs from fixtures/${app}.json. Do not edit.\nexport default JSON.parse(${JSON.stringify(raw)});\n`,
);

fs.cpSync(path.join(root, "media"), path.join(root, target.pub, "media"), { recursive: true });
console.log(`demo synced into ${app}`);
